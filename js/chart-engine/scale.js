// scale.js — Axis math: "nice" ticks (1/2/5 × 10^n) and linear scales. Pure.

const MAX_TICKS = 50; // hard cap: tick generation can never loop unbounded (review H1)
const MAX_DECIMALS = 20; // toFixed() throws above 100; 20 is far beyond display precision

/** Round a raw step to the nearest 1, 2, 5 or 10 × 10^n (Heckbert's rounding thresholds). */
function niceStep(rawStep) {
  const exponent = Math.floor(Math.log10(rawStep));
  const magnitude = 10 ** exponent;
  const fraction = rawStep / magnitude;
  const nice = fraction < 1.5 ? 1 : fraction < 3 ? 2 : fraction < 7 ? 5 : 10;
  return nice * magnitude;
}

/**
 * Tick values covering [min, max] on round numbers. A flat domain is padded so the value sits
 * mid-axis. Ticks are generated by index (not `v += step`), so a step below float precision
 * at large magnitudes cannot stall; such domains fall back to plain [min, max].
 * @param {number} min
 * @param {number} max
 * @param {number} [count]
 * @returns {number[]}
 */
export function niceTicks(min, max, count = 5) {
  const pad = min === max ? Math.abs(min) * 0.5 || 1 : 0;
  const lo = min - pad;
  const hi = max + pad;
  const step = niceStep((hi - lo) / Math.max(1, count));
  const start = Math.floor(lo / step) * step;
  const steps = Math.ceil((hi - start) / step);
  const precisionLost = !Number.isFinite(step) || step <= 0 || start + step === start || !(steps <= MAX_TICKS);
  if (precisionLost) return [lo, hi];
  const decimals = Math.min(MAX_DECIMALS, Math.max(0, -Math.floor(Math.log10(step))));
  return Array.from({ length: steps + 1 }, (_, i) => Number((start + i * step).toFixed(decimals)) || 0);
}

/** Map a value from domain [d0, d1] to range [r0, r1]. */
export function linearScale([d0, d1], [r0, r1]) {
  const k = d1 === d0 ? 0 : (r1 - r0) / (d1 - d0);
  return v => r0 + (v - d0) * k;
}
